import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import type { AgentTrial } from "./agent-trial.js";
import { resultsDir, repoRoot } from "./corpus.js";
import type { CaseResult, CategoryScore } from "./score.js";
import { categoryNames } from "./score.js";
import { syncCaseStudy } from "./trial/report.js";

export interface BenchResult {
  schema: 1;
  version: string;
  source: "local" | "git" | "npm";
  git?: string;
  npm?: string;
  generatedAt: string;
  tokenizer: string;
  detection: {
    fingerprint: string;
    categories: Record<string, CategoryScore>;
    cases?: CaseResult[];
  };
  tokens: {
    skill: number;
    agents: number;
    exists: { query: string; tokens: number; found: boolean };
    readSource: { files: string[]; tokens: number };
    hook: {
      cleanFile: string;
      cleanTokens: number;
      perFinding: Array<{ file: string; line: string; tokens: number }>;
      meanPerFinding: number | null;
    };
  };
  latencyMs: {
    samples: number;
    scan: { median: number; min: number; max: number };
    /** `uninvent check` on one clean file. Present on every result since 0.1. */
    hookClean: { median: number; min: number; max: number };
    hookDirty: { median: number; min: number; max: number };
    /**
     * The real `uninvent hook` process. Absent on results recorded before the hook was timed on its own.
     */
    hookRun?: {
      samples: number;
      cold: { p50: number; p95: number; min: number; max: number };
      warm: { p50: number; p95: number; min: number; max: number };
      warmDirty: { p50: number; p95: number; min: number; max: number };
      note: string;
    };
    note: string;
  };
  agentTrial: AgentTrial;
}

export function loadResults(dir = resultsDir()): BenchResult[] {
  const files = readdirSync(dir).filter((name) => name.endsWith(".json")).sort();
  const results = files.map((name) => JSON.parse(readFileSync(path.join(dir, name), "utf8")) as BenchResult);
  results.sort((a, b) => compareVersion(a.version, b.version));
  return results;
}

export function renderReport(results: BenchResult[]): string {
  if (results.length === 0) {
    return "# uninvent benchmark\n\nNo results yet. Run `npm run bench`.\n";
  }
  const latest = results[results.length - 1];
  if (!latest) return "# uninvent benchmark\n";
  const names = categoryNames(results.flatMap((result) => Object.keys(result.detection.categories)));
  const lines: string[] = [
    "# uninvent benchmark",
    "",
    "Fixed corpus, one result file per version. Generated from `bench/results/*.json` by `npm run bench`. Do not edit this file by hand.",
    "",
    `Tokenizer for every token count: ${latest.tokenizer}`,
    "",
    "## Latest",
    "",
    `**${latest.version}** (${latest.source}${latest.git ? `, \`${latest.git.slice(0, 7)}\`` : ""})`,
    "",
    proseLatest(latest, names),
    "",
    "### By category",
    "",
    categoryTable([latest], names),
    "",
    "### With the rule, and held out",
    "",
    originTable(latest, names),
    "",
    "### Tokens and time",
    "",
    tokenTable(results),
    "",
    "### Hook process",
    "",
    "Cold and warm are wall-clock times for `uninvent hook` after one edit. Cold turns the V8 compile cache off. Warm reuses it. Result files recorded before the hook was timed on its own leave those cells empty. The check column above is still `uninvent check` on one clean file.",
    "",
    hookTable(results),
    "",
    releaseComparison(results),
    "",
    "## Trend",
    "",
    categoryTable(results, names),
    "",
    ...charts(results, names),
    "",
    "## Paired agent trial",
    "",
    agentSection(results),
    "",
    "## What this does and does not show",
    "",
    "This is a checker benchmark. Each case is a file in `bench/corpus`. `caught / total` is how many non-clean cases in that category produced the finding kind the case asks for (`raw`, `rebuilt`, `reinvented`, or `export`). A clean file that prints anything is a false positive. Cases marked `with-rule` were written with the rule they exercise, including the original demo shapes. Cases marked `held-out` are different files: another control, another wording of the confirm dialog, a loader beside the button, a `cn()` class string. The corpus is not the unit-test fixture set.",
    "",
    "A version can flag the raw elements inside a recipe file and still score 0 on recipes. The recipe category only counts a `rebuilt …` line. v0.1 does that on purpose: it has no recipes. The same is true for documented states before v0.3, and for package sources before v0.4.",
    "",
    "Token counts use cl100k_base, the OpenAI GPT-4 tokenizer, as a proxy. Claude and Cursor tokenize differently. Compare versions to each other. The skill and `AGENTS.md` numbers are what a turn carries if those files are in context. `exists` is one query. The source number is `button.tsx` plus its story, the files you would open to learn the same button. The hook number is the mean of the finding lines `check` prints. A clean file is 0. The hook does not print the catalog.",
    "",
    "Latency is wall-clock time, including Node starting. The check column is the median of `uninvent check` on one file. The hook table is `uninvent hook` itself: cold with the V8 compile cache disabled, warm with the cache reused, p50 and p95 inside that sample. It will move a few milliseconds between machines. Detection counts and token counts do not, for the same version and the same corpus.",
    "",
    "The paired agent trial is off unless `UNINVENT_BENCH_API_KEY` is set. A skipped trial has no counts. This report does not invent them. When the trial does run, the wrong-component count is how many lines `uninvent check` prints on the file the model returned. That is the checker judging the model, not a person.",
    "",
    "Nothing here shows that a live coding agent, with tools and a hook, makes fewer mistakes or spends fewer tokens on a real task. That needs the real-repository trial in [bench/trial](bench/trial/README.md), written up in [CASE_STUDY.md](CASE_STUDY.md). Until that trial has run, the case study has no agent numbers.",
    "",
  ];
  return `${lines.join("\n").replace(/\n{3,}/g, "\n\n")}\n`;
}

export function writeReport(results = loadResults()): string {
  const markdown = renderReport(results);
  writeFileSync(path.join(repoRoot(), "BENCHMARK.md"), markdown);
  syncCaseStudy();
  return markdown;
}

function proseLatest(result: BenchResult, names: string[]): string {
  const bits = names.filter((name) => name !== "clean").map((name) => {
    const score = result.detection.categories[name];
    if (!score) return "";
    return `${score.caught}/${score.total} ${label(name)}`;
  }).filter(Boolean);
  const clean = result.detection.categories.clean;
  const fp = clean ? `${clean.falsePositives} false positive${clean.falsePositives === 1 ? "" : "s"} on ${clean.total} clean files` : "no clean files";
  const exists = result.tokens.exists.found
    ? `\`exists "${result.tokens.exists.query}"\` is ${result.tokens.exists.tokens} tokens`
    : `\`exists "${result.tokens.exists.query}"\` is ${result.tokens.exists.tokens} tokens and does not resolve`;
  return `Caught ${bits.join(", ")}. ${fp}. Skill ${result.tokens.skill} tokens. ${exists}. Reading the button source is ${result.tokens.readSource.tokens} tokens.`;
}

function categoryTable(results: BenchResult[], names: string[]): string {
  const headers = ["Version", ...names.map(label)];
  const rows = results.map((result) => [
    result.version,
    ...names.map((name) => formatCategory(result.detection.categories[name], name)),
  ]);
  return table(headers, rows);
}

function originTable(result: BenchResult, names: string[]): string {
  const headers = ["Category", "With the rule", "Held out"];
  const rows = names.map((name) => {
    const score = result.detection.categories[name];
    if (!score) return [label(name), "—", "—"];
    return [label(name), formatOrigin(score.withRule, name), formatOrigin(score.heldOut, name)];
  });
  return table(headers, rows);
}

function releaseComparison(results: BenchResult[]): string {
  const left = results.find((result) => result.version === "0.3.0");
  const right = results.find((result) => result.version === "0.4.1");
  const lines = [
    "## 0.3.0 and 0.4.1",
    "",
    "The unpublished release is 0.4.1. 0.4.0, the package-source commit, stays in the trend table. Detection counts and token counts do not move between machines. Latency does.",
    "",
  ];
  if (!left || !right) {
    lines.push("Both `bench/results/0.3.0.json` and `bench/results/0.4.1.json` are required for this table.", "");
    return lines.join("\n");
  }
  const names = categoryNames([
    ...Object.keys(left.detection.categories),
    ...Object.keys(right.detection.categories),
  ]);
  const rows = names.map((name) => [
    label(name),
    formatCategory(left.detection.categories[name], name),
    formatCategory(right.detection.categories[name], name),
  ]);
  rows.push(
    ["Skill tokens", String(left.tokens.skill), String(right.tokens.skill)],
    ["exists tokens", String(left.tokens.exists.tokens), String(right.tokens.exists.tokens)],
    [
      "Hook line (mean tokens)",
      left.tokens.hook.meanPerFinding === null ? "—" : String(left.tokens.hook.meanPerFinding),
      right.tokens.hook.meanPerFinding === null ? "—" : String(right.tokens.hook.meanPerFinding),
    ],
    ["Scan (ms)", String(left.latencyMs.scan.median), String(right.latencyMs.scan.median)],
    ["Clean-file check (ms)", String(left.latencyMs.hookClean.median), String(right.latencyMs.hookClean.median)],
    ["Hook cold p50 (ms)", hookStat(left, "cold", "p50"), hookStat(right, "cold", "p50")],
    ["Hook cold p95 (ms)", hookStat(left, "cold", "p95"), hookStat(right, "cold", "p95")],
    ["Hook warm p50 (ms)", hookStat(left, "warm", "p50"), hookStat(right, "warm", "p50")],
    ["Hook warm p95 (ms)", hookStat(left, "warm", "p95"), hookStat(right, "warm", "p95")],
  );
  lines.push(table(["", "0.3.0", "0.4.1"], rows), "");
  return lines.join("\n");
}

function hookStat(result: BenchResult, phase: "cold" | "warm", stat: "p50" | "p95"): string {
  const sample = result.latencyMs.hookRun?.[phase];
  if (!sample) return "—";
  return String(sample[stat]);
}

function hookTable(results: BenchResult[]): string {
  const headers = ["Version", "Cold p50", "Cold p95", "Warm p50", "Warm p95", "Warm, with a finding (p50)"];
  const rows = results.map((result) => {
    const hook = result.latencyMs.hookRun;
    if (!hook) return [result.version, "—", "—", "—", "—", "—"];
    return [
      result.version,
      String(hook.cold.p50),
      String(hook.cold.p95),
      String(hook.warm.p50),
      String(hook.warm.p95),
      String(hook.warmDirty.p50),
    ];
  });
  return table(headers, rows);
}

function tokenTable(results: BenchResult[]): string {
  const headers = ["Version", "Skill", "AGENTS.md", "exists", "Button source", "Hook line (mean)", "Scan (ms)", "Hook, clean file (ms)"];
  const rows = results.map((result) => [
    result.version,
    String(result.tokens.skill),
    String(result.tokens.agents),
    result.tokens.exists.found ? String(result.tokens.exists.tokens) : `${result.tokens.exists.tokens} (no match)`,
    String(result.tokens.readSource.tokens),
    result.tokens.hook.meanPerFinding === null ? "—" : String(result.tokens.hook.meanPerFinding),
    String(result.latencyMs.scan.median),
    String(result.latencyMs.hookClean.median),
  ]);
  return table(headers, rows);
}

function charts(results: BenchResult[], names: string[]): string[] {
  const interesting = names.filter((name) => name === "recipe" || name === "documented-state" || name === "package");
  return interesting.map((name) => {
    const labels = results.map((result) => result.version);
    const values = results.map((result) => result.detection.categories[name]?.caught ?? 0);
    const max = Math.max(1, ...results.map((result) => result.detection.categories[name]?.total ?? 0));
    return [
      "```mermaid",
      "xychart-beta",
      `    title "${label(name)} caught"`,
      `    x-axis [${labels.map((item) => `"${item}"`).join(", ")}]`,
      `    y-axis "Cases caught" 0 --> ${max}`,
      `    bar [${values.join(", ")}]`,
      "```",
      "",
    ].join("\n");
  });
}

function agentSection(results: BenchResult[]): string {
  const ran = results.filter((result) => result.agentTrial.status === "ran");
  if (ran.length === 0) {
    const errored = results.filter((result) => result.agentTrial.status === "error");
    if (errored.length === 0) {
      return "Not run. No result file includes a paired trial, so there are no agent numbers. Set `UNINVENT_BENCH_API_KEY` and see [bench/README.md](bench/README.md). That corpus trial is not the real-repository study. See [CASE_STUDY.md](CASE_STUDY.md).";
    }
    return errored.map((result) => `**${result.version}** failed before it could score: ${result.agentTrial.reason ?? "unknown error"}. Those rows are not treated as zero.`).join("\n\n");
  }
  const lines = ["Wrong-component count is the number of `uninvent check` lines on the file the model returned. A cell with an error was not scored.", ""];
  for (const result of ran) {
    lines.push(`### ${result.version}`, "", `Model \`${result.agentTrial.model ?? ""}\`. ${result.agentTrial.judge ?? ""}`, "");
    const headers = ["Task", "Without uninvent", "With the skill", "Tokens without", "Tokens with", "Time without (ms)", "Time with (ms)"];
    const rows = (result.agentTrial.tasks ?? []).map((task) => {
      const off = task.conditions.find((entry) => entry.condition === "without-uninvent");
      const on = task.conditions.find((entry) => entry.condition === "with-uninvent");
      return [
        task.id,
        cell(off),
        cell(on),
        tokenCell(off),
        tokenCell(on),
        off ? String(off.timeMs) : "—",
        on ? String(on.timeMs) : "—",
      ];
    });
    lines.push(table(headers, rows), "");
  }
  return lines.join("\n");
}

function cell(condition: { wrongComponents: number | null; error?: string } | undefined): string {
  if (!condition) return "—";
  if (condition.error) return `not scored`;
  if (condition.wrongComponents === null) return "not scored";
  return String(condition.wrongComponents);
}

function tokenCell(condition: { tokens: number | null; error?: string } | undefined): string {
  if (!condition || condition.error || condition.tokens === null) return "—";
  return String(condition.tokens);
}

function formatCategory(score: CategoryScore | undefined, name: string): string {
  if (!score) return "—";
  if (name === "clean") return `${score.falsePositives} fp / ${score.total}`;
  return `${score.caught} / ${score.total}`;
}

function formatOrigin(score: { caught: number; total: number; falsePositives: number }, name: string): string {
  if (score.total === 0) return "—";
  if (name === "clean") return `${score.falsePositives} fp / ${score.total}`;
  return `${score.caught} / ${score.total}`;
}

function label(name: string): string {
  if (name === "raw-control") return "Raw controls";
  if (name === "recipe") return "Recipes";
  if (name === "documented-state") return "Documented states";
  if (name === "name-collision") return "Name collisions";
  if (name === "package") return "Package sources";
  if (name === "clean") return "Clean false positives";
  return name;
}

function table(headers: string[], rows: string[][]): string {
  const head = `| ${headers.join(" | ")} |`;
  const rule = `| ${headers.map(() => "---").join(" | ")} |`;
  const body = rows.map((row) => `| ${row.join(" | ")} |`);
  return [head, rule, ...body].join("\n");
}

function compareVersion(a: string, b: string): number {
  const pa = a.split(".").map((part) => Number(part));
  const pb = b.split(".").map((part) => Number(part));
  const length = Math.max(pa.length, pb.length);
  for (let index = 0; index < length; index += 1) {
    const diff = (pa[index] ?? 0) - (pb[index] ?? 0);
    if (diff !== 0) return diff;
  }
  return a.localeCompare(b);
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  writeReport();
  process.stdout.write(`Wrote BENCHMARK.md\n`);
}
